func TestUpdateCurrentTickers(t *testing.T) {
	prevTs := time.Now().Add(-time.Hour).UTC()
	newTs := time.Now().UTC()
	prev := func() *common.CurrencyRatesTicker {
		return &common.CurrencyRatesTicker{
			Timestamp:  prevTs,
			Rates:      map[string]float32{"usd": 1},
			TokenRates: map[string]float32{"0xa": 10, "0xb": 20},
		}
	}
	tests := []struct {
		name     string
		prev     *common.CurrencyRatesTicker
		ticker   *common.CurrencyRatesTicker
		err      error
		want     *common.CurrencyRatesTicker
		notified bool
	}{
		{
			name:     "complete ticker replaces previous one",
			prev:     prev(),
			ticker:   &common.CurrencyRatesTicker{Timestamp: newTs, Rates: map[string]float32{"usd": 2}, TokenRates: map[string]float32{"0xa": 11}},
			want:     &common.CurrencyRatesTicker{Timestamp: newTs, Rates: map[string]float32{"usd": 2}, TokenRates: map[string]float32{"0xa": 11}},
			notified: true,
		},
		{
			name:     "incomplete tokens keep previous rates of missing tokens",
			prev:     prev(),
			ticker:   &common.CurrencyRatesTicker{Timestamp: newTs, Rates: map[string]float32{"usd": 2}, TokenRates: map[string]float32{"0xa": 11}},
			err:      fmt.Errorf("%w: 1 of 2 batches failed", errCoingeckoIncompleteTokenRates),
			want:     &common.CurrencyRatesTicker{Timestamp: newTs, Rates: map[string]float32{"usd": 2}, TokenRates: map[string]float32{"0xa": 11, "0xb": 20}},
			notified: true,
		},
		{
			name:     "incomplete tokens without previous ticker",
			ticker:   &common.CurrencyRatesTicker{Timestamp: newTs, Rates: map[string]float32{"usd": 2}},
			err:      fmt.Errorf("%w: coins/list failed", errCoingeckoIncompleteTokenRates),
			want:     &common.CurrencyRatesTicker{Timestamp: newTs, Rates: map[string]float32{"usd": 2}},
			notified: true,
		},
		{
			name: "native failure keeps previous ticker",
			prev: prev(),
			err:  errors.New("simple/price failed"),
			want: prev(),
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			config := common.Config{CoinName: "fakecoin"}
			d, _, tmp := setupRocksDB(t, &testBitcoinParser{BitcoinParser: bitcoinTestnetParser()}, &config)
			defer closeAndDestroyRocksDB(t, d, tmp)
			notified := false
			fr := &FiatRates{
				db:                  d,
				currentTicker:       tt.prev,
				downloader:          &stubCurrentTickersDownloader{ticker: tt.ticker, err: tt.err},
				callbackOnNewTicker: func(*common.CurrencyRatesTicker) { notified = true },
			}
			fr.updateCurrentTickers()
			if got := fr.GetCurrentTicker("", ""); !reflect.DeepEqual(got, tt.want) {
				t.Fatalf("current ticker = %+v, want %+v", got, tt.want)
			}
			if notified != tt.notified {
				t.Fatalf("notified = %v, want %v", notified, tt.notified)
			}
			if !tt.notified {
				return
			}
			stored, err := d.FiatRatesGetSpecialTickers(currentTickersKey)
			if err != nil || stored == nil || len(*stored) != 1 {
				t.Fatalf("stored current ticker = %v, %v", stored, err)
			}
			if got := (*stored)[0].TokenRates; len(got)+len(tt.want.TokenRates) > 0 && !reflect.DeepEqual(got, tt.want.TokenRates) {
				t.Fatalf("stored TokenRates = %v, want %v", (*stored)[0].TokenRates, tt.want.TokenRates)
			}
		})
	}
}
